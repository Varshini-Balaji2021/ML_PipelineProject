# 5. SUBMISSION / EVALUATION REPORT
# ============================================================

def generate_submission_report():

    metrics_path = (
        RESULTS_DIR
        / "test_evaluation_metrics.csv"
    )

    submission_path = (
        SUBMISSION_DIR
        / "submission.csv"
    )

    sections = {

        "Pipeline Completion": """
            <p>
                The machine-learning pipeline completed the
                training and evaluation stages successfully.
            </p>
        """,

        "Test Set Evaluation": """
            <p>
                The frozen best model was evaluated on the
                held-out test dataset.
            </p>
        """
    }

    if metrics_path.exists():

        metrics_df = pd.read_csv(
            metrics_path
        )

        sections["Test Evaluation Metrics"] = (
            metrics_df.to_html(
                classes="table",
                index=False
            )
        )

    if submission_path.exists():

        sections["Submission Export"] = f"""

            <p>
                Test predictions were exported successfully.
            </p>

            <p>
                <strong>File:</strong>
                {submission_path}
            </p>

        """

    else:

        sections["Submission Export"] = """

            <p>
                Submission file has not yet been generated.
            </p>

        """

    return generate_html_report(
        "Final Submission & Evaluation Report",
        sections,
        "05_final_submission_report"
    )


