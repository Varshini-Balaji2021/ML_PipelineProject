# ============================================================
# GENERIC HTML REPORT GENERATOR
# ============================================================

def generate_html_report(title: str, sections: dict, output_name: str):

    html = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">

        <title>{title}</title>

        <style>

            body {{
                font-family: Arial, sans-serif;
                margin: 40px;
                background-color: #f9f9f9;
                color: #333;
            }}

            h1 {{
                color: #1f4e79;
            }}

            h2 {{
                color: #2e75b6;
                border-bottom: 2px solid #ddd;
                padding-bottom: 5px;
                margin-top: 30px;
            }}

            table {{
                border-collapse: collapse;
                width: 100%;
                margin: 15px 0;
                background: #fff;
            }}

            th, td {{
                border: 1px solid #ddd;
                padding: 10px;
                text-align: left;
            }}

            th {{
                background-color: #f2f2f2;
            }}

            .container {{
                background: #fff;
                padding: 30px;
                border-radius: 8px;
                box-shadow: 0 0 10px rgba(0,0,0,0.05);
            }}

            .footer {{
                margin-top: 40px;
                font-size: 12px;
                color: #666;
                text-align: center;
            }}

            .highlight-box {{
                background-color: #f0f4f8;
                border-left: 4px solid #1f4e79;
                padding: 15px;
                margin: 15px 0;
            }}

        </style>

    </head>

    <body>

    <div class="container">

        <h1>{title}</h1>

        <p>
            <strong>Generated:</strong>
            {datetime.now().strftime('%Y-%m-%d %H:%M')}
        </p>
    """

    for section_title, content in sections.items():

        html += f"""
        <h2>{section_title}</h2>
        {content}
        """

    html += """
        <div class="footer">
            AI-Assisted ML Project Platform | Governance & Reporting Layer
        </div>

    </div>

    </body>
    </html>
    """

    html_path = REPORTS_DIR / f"{output_name}.html"

    html_path.write_text(
        html,
        encoding="utf-8"
    )

    print(f"Report successfully saved -> {html_path}")

    return html_path


