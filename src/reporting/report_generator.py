# 4. TRAINING REPORT
# ============================================================

def generate_training_report():

    comparison_path = (
        RESULTS_DIR
        / "validation_model_comparison.csv"
    )

    if not comparison_path.exists():

        print(
            f"Training comparison file not found at: "
            f"{comparison_path}"
        )

        return None

    comparison_df = pd.read_csv(
        comparison_path
    )

    table_html = comparison_df.to_html(
        classes="table",
        index=False
    )

    # Try to determine the best model dynamically
    best_model_name = "Not available"
    best_rmse = "Not available"

    rmse_columns = [
        col for col in comparison_df.columns
        if "rmse" in col.lower()
    ]

    model_columns = [
        col for col in comparison_df.columns
        if col.lower() in ["model", "model_name", "algorithm"]
    ]

    if rmse_columns:

        rmse_col = rmse_columns[0]

        best_index = comparison_df[rmse_col].idxmin()

        best_rmse = comparison_df.loc[
            best_index,
            rmse_col
        ]

        if model_columns:

            best_model_name = comparison_df.loc[
                best_index,
                model_columns[0]
            ]

    sections = {

        "Model Training Overview": """
            <p>
                Multiple supervised regression models were trained
                and compared using the validation dataset.
            </p>

            <p>
                The current pipeline compares:
            </p>

            <ul>

                <li>Ridge Regression</li>

                <li>Random Forest Regressor</li>

                <li>Gradient Boosting Regressor</li>

            </ul>
        """,

        "Validation Model Comparison":
            table_html,

        "Winning Model Selection": f"""

            <div class="highlight-box">

                <p>
                    <strong>Best Model:</strong>
                    {best_model_name}
                </p>

                <p>
                    <strong>Best Validation RMSE:</strong>
                    {best_rmse}
                </p>

            </div>

        """
    }

    return generate_html_report(
        "Model Training & Validation Report",
        sections,
        "04_model_validation_report"
    )


